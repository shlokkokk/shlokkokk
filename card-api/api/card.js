function wrapText(text, maxCharsPerLine, maxLines) {
  const words = text.split(' ');
  const lines = [];
  let currentLine = '';

  for (const word of words) {
    if ((currentLine + ' ' + word).trim().length > maxCharsPerLine) {
      if (currentLine) lines.push(currentLine.trim());
      currentLine = word;
    } else {
      currentLine = (currentLine + ' ' + word).trim();
    }
    if (lines.length >= maxLines - 1 && currentLine.length > 0) {
      const lastLine = lines.length === maxLines - 1;
      if (lastLine && (currentLine + ' ' + words[words.indexOf(word) + 1] || '').length > maxCharsPerLine) {
        break;
      }
    }
  }
  if (currentLine) lines.push(currentLine.trim());
  
  // Truncate to maxLines
  if (lines.length > maxLines) {
    lines.length = maxLines;
    lines[maxLines - 1] = lines[maxLines - 1].slice(0, maxCharsPerLine - 3) + '...';
  }
  
  return lines;
}

function escapeXml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/\u2014/g, '&#x2014;')
    .replace(/\u2013/g, '&#x2013;');
}

